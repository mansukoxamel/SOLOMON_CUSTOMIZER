def picker_name_ja(mode, value):
    """Return the reviewed Japanese name without the picker ID prefix."""
    text = PICKER_TOOLTIPS_JA.get((mode, value))
    if text is None:
        return None
    if mode in ("item", "enemy") and text.startswith("0x"):
        _prefix, separator, name = text.partition(" ")
        if separator:
            return name
    return text
