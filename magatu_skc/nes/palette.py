# 透明扱いの色（hot pink、最後尾に追加）
TRANSPARENT_COLOR = (0xff, 0x69, 0xb4)


def get_nes_color(index: int) -> tuple:
    """64色NES標準パレットから色取得"""
    if 0 <= index < len(NES_COLORS):
        return NES_COLORS[index]
    return TRANSPARENT_COLOR


class SubPalette:
    """1つのサブパレット（4色: BG + 3色）"""

    def __init__(self, palette_indexes):
        """
        Args:
            palette_indexes: NES色インデックスのリスト（3 or 4要素）
              3要素の場合は先頭に共通背景色 0x0f を追加
        """
        self.colors = list(palette_indexes)
        if len(self.colors) == 3:
            self.colors.insert(0, 0x0f)
        elif len(self.colors) != 4:
            raise ValueError(f"SubPalette must be 3 or 4 colors, got {len(self.colors)}")

    def get_nes_index(self, color_no: int) -> int:
        """サブパレット内のインデックス → NES色インデックス"""
        return self.colors[color_no]

    def get_rgb(self, color_no: int) -> tuple:
        """サブパレット内のインデックス → RGBタプル"""
        return get_nes_color(self.get_nes_index(color_no))


# ROM内パレット位置から読み込み
def load_palette_from_rom(rom_data: bytes, offset: int) -> SubPalette:
    """ROMの指定オフセットから4バイト読んでサブパレット作成"""
    return SubPalette([rom_data[offset + i] for i in range(4)])
